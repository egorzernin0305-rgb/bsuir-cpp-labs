#include <iostream>

/*
Реализовать класс для работы с двумерными массивами (матрицами)
и следующие методы:
1. конструктор с параметрами
2. деструктор
3. метод ввода данных в матрицу
4. вывод матрицы на экран
5. метод умножения матриц
*/

class Matrix
{
private:
    int rows;                                       // количество строк
    int cols;                                       // количество столбцов
    int** data;                                     // указатель на динамически выделенный двумерный массив

public:
    Matrix(int r = 0, int c = 0);                   // Конструктор с параметрами
    ~Matrix();                                      // Деструктор

    void input();                                   // Ввод данных в матрицу
    void print() const;                             // Вывод матрицы на экран

                                                    
    Matrix* multiply(const Matrix& other) const;    // Метод умножения матриц
};
